// ---------- базовые элементы ----------
const run = (text, o = {}) => new TextRun({ text, font: FONT, ...o });

function p(children, o = {}) {
  if (typeof children === "string") children = [run(children)];
  return new Paragraph({
    children,
    alignment: o.align ?? AlignmentType.JUSTIFIED,
    indent: o.noIndent ? undefined : { firstLine: 709 },
    spacing: { after: o.after ?? 120, before: o.before ?? 0, line: 312 },
    keepNext: o.keepNext,
  });
}
// абзац с жирным началом: rich("Цель работы.", " остальное")
const rich = (lead, rest, o) => p([run(lead, { bold: true }), run(rest)], o);

const h1 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [run(t)], keepNext: true });
const h2 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [run(t)], keepNext: true });

const bullet = (children) => new Paragraph({
  numbering: { reference: "dash", level: 0 },
  children: typeof children === "string" ? [run(children)] : children,
  alignment: AlignmentType.JUSTIFIED,
  spacing: { after: 60, line: 312 },
});
let listNo = 0;
const numbered = (items) => {
  const ref = `num${listNo++}`;
  numberingConfigs.push({
    reference: ref,
    levels: [{ level: 0, format: LevelFormat.DECIMAL, text: "%1)", alignment: AlignmentType.LEFT,
      style: { paragraph: { indent: { left: 1069, hanging: 360 } } } }],
  });
  return items.map((t) => new Paragraph({
    numbering: { reference: ref, level: 0 },
    children: typeof t === "string" ? [run(t)] : t,
    alignment: AlignmentType.JUSTIFIED,
    spacing: { after: 60, line: 312 },
  }));
};

// ---------- рисунки ----------
let figNo = 0;
function figure(file, pxW, pxH, caption, maxW = 624) {
  const w = Math.min(maxW, pxW);
  const h = Math.round(pxH * (w / pxW));
  figNo++;
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 120, after: 80 },
      children: [new ImageRun({ type: "png", data: fs.readFileSync(path.join(IMG, file)),
        transformation: { width: w, height: h },
        altText: { title: `Рисунок ${figNo}`, description: caption, name: file } })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { after: 240, line: 276 },
      children: [run(`Рисунок ${figNo} – ${caption}`, { size: 22 })],
    }),
  ];
}

// ---------- таблицы ----------
let tabNo = 0;
const border = { style: BorderStyle.SINGLE, size: 4, color: "8C8C8C" };
const borders = { top: border, bottom: border, left: border, right: border };

function cell(content, width, o = {}) {
  const paras = (Array.isArray(content) ? content : [content]).map((c) =>
    new Paragraph({
      alignment: o.align ?? AlignmentType.LEFT,
      spacing: { after: 0, line: 252 },
      children: typeof c === "string" ? [run(c, { size: 21, bold: o.bold, color: o.color })] : c,
    }));
  return new TableCell({
    children: paras, borders,
    width: { size: width, type: WidthType.DXA },
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    verticalAlign: o.vAlign ?? VerticalAlign.TOP,
    shading: o.fill ? { fill: o.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
  });
}

// widths — доли, сумма = 1; rows[0] — шапка
function table(caption, fractions, rows, o = {}) {
  tabNo++;
  const widths = fractions.map((f) => Math.round(f * CONTENT_W));
  widths[widths.length - 1] += CONTENT_W - widths.reduce((a, b) => a + b, 0);
  const alignFor = (i) => (o.right || []).includes(i) ? AlignmentType.RIGHT : (o.center || []).includes(i) ? AlignmentType.CENTER : AlignmentType.LEFT;
  const trs = rows.map((r, ri) => new TableRow({
    tableHeader: ri === 0, cantSplit: true,
    children: r.map((c, ci) => cell(c, widths[ci], {
      bold: ri === 0 || (o.boldRow === ri), fill: ri === 0 ? "E7E6E6" : (o.boldRow === ri ? "F2F2F2" : undefined),
      align: ri === 0 ? AlignmentType.LEFT : alignFor(ci),
    })),
  }));
  return [
    new Paragraph({ keepNext: true, spacing: { before: 180, after: 80 },
      children: [run(`Таблица ${tabNo} – ${caption}`, { size: 22 })] }),
    new Table({ width: { size: CONTENT_W, type: WidthType.DXA }, columnWidths: widths, rows: trs }),
    new Paragraph({ spacing: { after: 120 }, children: [] }),
  ];
}

